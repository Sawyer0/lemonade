import { WebView } from 'react-native-webview';
import { StyleSheet, Platform, StatusBar, View } from 'react-native';
import { SafeAreaView } from 'react-native-safe-area-context';
import {
    GoogleSignin,
    GoogleSigninButton,
    statusCodes,
} from '@react-native-google-signin/google-signin';
import { useState, useRef, useEffect } from 'react';

// NOTE: Replace this with your actual Web Client ID from Firebase Console -> Authentication -> Sign-in method -> Google -> Web SDK configuration
// or set EXPO_PUBLIC_GOOGLE_WEB_CLIENT_ID in your .env file
const WEB_CLIENT_ID = process.env.EXPO_PUBLIC_GOOGLE_WEB_CLIENT_ID || '';

export default function App() {
    const webviewRef = useRef<WebView>(null);
    const [userInfo, setUserInfo] = useState<any>(null);
    const [isSigningIn, setIsSigningIn] = useState(false);

    // Tunnel URL generated by localtunnel
    // NOTE: You may need to visit this URL in your mobile browser once to bypass the "friendly warning" page.
    const uri = '774efe6bb84846.lhr.life';

    useEffect(() => {
        GoogleSignin.configure({
            webClientId: WEB_CLIENT_ID,
            offlineAccess: true,
        });
    }, []);

    const signIn = async () => {
        try {
            await GoogleSignin.hasPlayServices();
            const userInfo = await GoogleSignin.signIn();
            setUserInfo(userInfo);

            // Trap 1 Fix: Bridge the token to WebView
            if (userInfo.data?.idToken && webviewRef.current) {
                const token = userInfo.data.idToken;
                const script = `
                    (function() {
                        console.log("Native Google Sign-In successful, bridging token...");
                        if (window.handleNativeGoogleLogin) {
                            window.handleNativeGoogleLogin('${token}');
                        } else {
                            console.warn("window.handleNativeGoogleLogin is not defined yet.");
                            // Retry mechanism could be added here or we rely on the webapp to pool/listen
                            // For MVP, simplistic injection:
                            sessionStorage.setItem('google_id_token', '${token}');
                        }
                    })();
                    true;
                `;
                webviewRef.current.injectJavaScript(script);
            }
        } catch (error: any) {
            if (error.code === statusCodes.SIGN_IN_CANCELLED) {
                // user cancelled the login flow
            } else if (error.code === statusCodes.IN_PROGRESS) {
                // operation (e.g. sign in) is in progress already
            } else if (error.code === statusCodes.PLAY_SERVICES_NOT_AVAILABLE) {
                // play services not available or outdated
            } else {
                // some other error happened
                console.error("Google Sign-In Error", error);
            }
        }
    };

    return (
        <SafeAreaView style={styles.container}>
            <StatusBar barStyle="dark-content" />
            <WebView
                ref={webviewRef}
                source={{
                    uri,
                    headers: {
                        'Bypass-Tunnel-Reminder': 'true',
                        'User-Agent': 'LemonadeMobile/1.0'
                    }
                }}
                style={styles.webview}
                javaScriptEnabled={true}
                scrollEnabled={true}
                scalesPageToFit={true}
                startInLoadingState={true}
                nestedScrollEnabled={true}
                showsVerticalScrollIndicator={true}
                contentInsetAdjustmentBehavior="automatic"
                // Trap 2 Fix: Force permission prompt for Camera/Mic
                mediaCapturePermissionGrantType="grantIfSameHostElsePrompt"
                // Auto-click the "Click to Continue" button if headers fail
                injectedJavaScript={`
                    setTimeout(function () {
                        var btn = document.querySelector('button');
                        if (btn && btn.innerText.toLowerCase().includes('continue')) {
                            btn.click();
                        }
                    }, 500);
                    true; 
                `}
                domStorageEnabled={true}
                allowFileAccess={true}
                allowUniversalAccessFromFileURLs={true}
                allowsInlineMediaPlayback={true}
                onError={(syntheticEvent) => {
                    const { nativeEvent } = syntheticEvent;
                    console.warn('WebView error: ', nativeEvent);
                }}
            />
            {/* Native Login Overlay */}
            <View style={styles.authBar}>
                <GoogleSigninButton
                    size={GoogleSigninButton.Size.Wide}
                    color={GoogleSigninButton.Color.Light}
                    onPress={signIn}
                    disabled={isSigningIn}
                />
            </View>
        </SafeAreaView>
    );
}

const styles = StyleSheet.create({
    container: {
        flex: 1,
        backgroundColor: '#fff',
        paddingTop: Platform.OS === 'android' ? StatusBar.currentHeight : 0,
    },
    webview: {
        flex: 1,
    },
    authBar: {
        padding: 10,
        backgroundColor: '#f0f0f0',
        alignItems: 'center',
        borderTopWidth: 1,
        borderTopColor: '#ccc',
    }
});
