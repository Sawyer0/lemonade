import type { ICaseRepository, ILogger } from '@lemonade/core';
import type { VoiceProviderId } from './provider';

/**
 * One turn of a live voice session, written to the case ledger. The audio
 * itself is never stored — only who spoke, what was said, and which provider
 * produced it, so a transcript can be traced back to its model.
 */
export interface TranscriptSink {
    record(role: 'user' | 'assistant', text: string): Promise<void>;
}

export interface TranscriptSinkInput {
    /** Case the turns belong to. Without one there is nowhere to append. */
    caseId: string | undefined;
    /** Technician in the session; the actor on user turns. */
    userId: string;
    provider: VoiceProviderId;
    /** Resolves the ledger repository, or undefined when the ledger is unavailable. */
    repository: () => ICaseRepository | undefined;
    logger: ILogger;
}

/**
 * Appends every turn as a `transcript` ledger event, whatever the provider.
 * When there is no case id yet (the client sends it in token metadata once
 * the case flow exists) the sink records nothing and says so once, instead
 * of failing the call. A failed append is logged, never thrown: a ledger
 * outage must not kill a live diagnosis.
 */
export function createTranscriptSink(input: TranscriptSinkInput): TranscriptSink {
    const { caseId, userId, provider, repository, logger } = input;
    let resolved: ICaseRepository | undefined;
    let lookedUp = false;

    const ledger = (): ICaseRepository | undefined => {
        if (!lookedUp) {
            lookedUp = true;
            let lookupFailed = false;
            try {
                resolved = repository();
            } catch (error) {
                lookupFailed = true;
                logger.warn('case ledger unavailable; transcripts will not be recorded', { error });
                resolved = undefined;
            }
            if (!lookupFailed && caseId && !resolved) {
                logger.warn('case ledger unavailable; transcripts will not be recorded', { caseId });
            }
        }
        return resolved;
    };

    if (!caseId) {
        logger.debug('no case id for this session; transcripts will not reach the ledger');
    }

    return {
        async record(role, text): Promise<void> {
            if (!caseId) return;
            const repo = ledger();
            if (!repo) return;
            try {
                // User turns are spoken by the technician; assistant turns are
                // generated by the model. The provider id in the payload says
                // which model produced (or transcribed) the turn.
                await repo.appendEntry(caseId, {
                    type: 'transcript',
                    actor: role === 'user' ? { kind: 'user', id: userId } : { kind: 'agent', id: 'master-tech' },
                    source: role === 'user' ? 'tech' : 'model',
                    occurredAt: new Date(),
                    payload: { role, text, provider },
                });
            } catch (error) {
                logger.error('failed to record transcript in the ledger', error, { caseId, role });
            }
        },
    };
}
